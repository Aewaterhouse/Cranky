import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { describe, expect, it } from 'vitest'
import {
  bandFactor,
  cornerSpeed,
  draftFactor,
  resistance,
  speedLimit,
  stepSpeed,
  totalMass,
} from '../src/core/physics'
import { routeAt, withLaps } from '../src/core/route'
import { ROUTE_INDEX, loadRoute } from '../src/core/routeLibrary'
import { RoadFeel } from '../src/modes/freeRide/feel'
import { newPose, RoadPath } from '../src/scene/route/roadPath'

/**
 * The vectors both sides must agree on: this file checks the client against them and the server's
 * tests/test_road_vectors.py checks the Python port. After a deliberate physics change, regenerate with
 * `ROAD_VECTORS=write pnpm exec vitest run tests/roadVectors.test.ts` and fix the server until it passes too.
 */
const FILE = resolve(__dirname, '../../content/tests/road-vectors.json')
const LAPPED: Record<string, number> = { 'nundah-crit': 3 }
const SAMPLES = 40

const grid = <T>(...lists: number[][]) =>
  lists.reduce<number[][]>((acc, l) => acc.flatMap((a) => l.map((v) => [...a, v])), [[]]) as T[]

async function build() {
  const routes = []
  for (const { id } of ROUTE_INDEX) {
    const lap = await loadRoute(id)
    const laps = LAPPED[id] ?? 1
    const route = withLaps(lap, laps)
    const path = new RoadPath(lap)
    const feel = new RoadFeel(route)
    const pose = newPose()
    const at = Array.from({ length: SAMPLES }, (_, i) => {
      const d = +((route.distance * (i + 0.37)) / SAMPLES).toFixed(1)
      return {
        d,
        grade: routeAt(route, d).grade,
        curv: path.poseAt(laps > 1 ? d % lap.distance : d, pose).curv,
        limit: feel.limit(d, 16),
      }
    })
    routes.push({ id, laps, distance: route.distance, space: lap.points[1].d, at })
  }
  const bends = [
    [0, 0, 0, 0, 0, 0, 0, 0.05, 0.05, 0],
    [0.002, 0.01, 0.03, 0.08, 0.2, 0.08, 0.01, 0, 0, 0],
  ]
  return {
    note: 'Generated by client/tests/roadVectors.test.ts (ROAD_VECTORS=write). Do not edit by hand.',
    mass: [null, 58, 90].map((kg) => ({ kg, out: totalMass(kg ?? undefined) })),
    resistance: grid<number[]>([0, 4, 12, 20], [-8, 0, 6], [67, 99], [0, 3], [1, 0.7]).map(
      ([v, grade, mass, wind, draft]) => ({
        v,
        grade,
        mass,
        wind,
        draft,
        out: resistance(v, grade, mass, wind, draft),
      }),
    ),
    step: grid<number[]>([0, 6, 15], [0, 180, 900], [-9, 0, 7], [0.25, 1], [22, 8], [1, 0.73]).map(
      ([v, power, grade, dt, limit, draft]) => ({
        v,
        power,
        grade,
        mass: 84,
        dt,
        wind: 0,
        limit,
        draft,
        out: stepSpeed(v, power, grade, 84, dt, 0, limit, draft),
      }),
    ),
    corner: [0, 0.001, 0.02, -0.05, 0.3, 2].map((curv) => ({ curv, out: cornerSpeed(curv) })),
    limit: bends.flatMap((curv) =>
      [3, 11, 20].map((v) => ({
        v,
        curv,
        out: speedLimit(v, (s) => curv[Math.min(curv.length - 1, Math.round(s / 5))]),
      })),
    ),
    draft: [
      [],
      [0.5],
      [2],
      [5],
      [9.9],
      [10],
      [15, 25],
      [1, 3, 8],
      [1, 2, 3, 4, 5, 6],
      [-2, 30],
    ].map((gaps) => ({ gaps, out: draftFactor(gaps) })),
    band: [-400, -150, -80, -15, -5, 0, 10, 40, 150, 900].map((gap) => ({
      gap,
      out: bandFactor(gap),
    })),
    routes,
  }
}

type Json = null | number | string | Json[] | { [k: string]: Json }
function same(got: Json, want: Json, path: string) {
  if (typeof want === 'number') expect(got as number, path).toBeCloseTo(want, 9)
  else if (Array.isArray(want)) {
    expect((got as Json[]).length, path).toBe(want.length)
    want.forEach((w, i) => same((got as Json[])[i], w, `${path}[${i}]`))
  } else if (want && typeof want === 'object')
    for (const k of Object.keys(want))
      same((got as Record<string, Json>)[k], want[k], `${path}.${k}`)
  else expect(got, path).toBe(want)
}

describe('road vectors shared with the server', () => {
  it('the client still produces the shared vectors', async () => {
    const fresh = JSON.parse(JSON.stringify(await build())) as Json
    if (process.env.ROAD_VECTORS === 'write') writeFileSync(FILE, JSON.stringify(fresh, null, 1))
    same(fresh, JSON.parse(readFileSync(FILE, 'utf8')) as Json, 'vectors')
  })

  it('drafting only ever helps and the band is bounded', () => {
    expect(draftFactor([1])).toBeCloseTo(0.73)
    expect(draftFactor([1, 2, 3, 4, 5, 6])).toBeCloseTo(0.6)
    expect(draftFactor([12])).toBe(1)
    expect(bandFactor(-1000)).toBeCloseTo(1.2)
    expect(bandFactor(1000)).toBeCloseTo(0.8)
    expect(bandFactor(5)).toBe(1)
  })
})
